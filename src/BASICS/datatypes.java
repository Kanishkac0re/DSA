package BASICS;

public class datatypes
{
    public static void main(String[] args)
    {
        byte num1 = 127;
        System.out.println(num1);
        //num1 = 500; not possible cause out of range

        short num2 = 5099;
        System.out.println(num2);

        long num3 = 833333333;
        System.out.println(num3);

        //floating datatypes
        float num5 = 3.14243f;
        System.out.println(num5);

        double num6 = 3.5647837646783763;
        System.out.println(num6);

        boolean num7 = true;
        // cpp me true ki jgh 1 bhi use kr skte hai but not in java

        // char is always single quote
        // string is double quotes

        //ascii values
        System.out.println((char)('a'+ 1));

    }

}
